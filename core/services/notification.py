"""
Shared Notification Service — Telegram, email, WhatsApp.
All agents deliver through this. Never call Telegram API directly from agents.
"""
import httpx
from core.config import settings
from core.observability import logger


class NotificationService:

    async def telegram(self, chat_id: str, text: str, parse_mode: str = "Markdown",
                       token: str | None = None, disable_preview: bool = True) -> bool:
        """Send Telegram message. Uses default token or per-bot token."""
        tok = token or settings.TELEGRAM_BOT_TOKEN
        if not tok:
            logger.warning("telegram_no_token")
            return False
        # Telegram has 4096 char limit — split if needed
        chunks = [text[i:i+4000] for i in range(0, len(text), 4000)]
        success = True
        async with httpx.AsyncClient(timeout=15) as client:
            for chunk in chunks:
                resp = await client.post(
                    f"https://api.telegram.org/bot{tok}/sendMessage",
                    json={"chat_id": chat_id, "text": chunk, "parse_mode": parse_mode,
                          "disable_web_page_preview": disable_preview},
                )
                if not resp.json().get("ok"):
                    logger.warning("telegram_send_failed", chat_id=chat_id, error=resp.text[:200])
                    success = False
        return success

    async def telegram_photo(self, chat_id: str, photo_url: str, caption: str = "",
                             token: str | None = None) -> bool:
        tok = token or settings.TELEGRAM_BOT_TOKEN
        async with httpx.AsyncClient(timeout=15) as client:
            resp = await client.post(
                f"https://api.telegram.org/bot{tok}/sendPhoto",
                json={"chat_id": chat_id, "photo": photo_url, "caption": caption[:1024], "parse_mode": "Markdown"},
            )
        return resp.json().get("ok", False)

    async def email(self, to: str, subject: str, body: str, html: bool = True) -> bool:
        """Send email via SMTP."""
        try:
            import aiosmtplib
            from email.mime.multipart import MIMEMultipart
            from email.mime.text import MIMEText
            msg = MIMEMultipart("alternative")
            msg["Subject"] = subject
            msg["From"] = settings.SMTP_USER
            msg["To"] = to
            msg.attach(MIMEText(body, "html" if html else "plain"))
            await aiosmtplib.send(
                msg, hostname=settings.SMTP_HOST, port=settings.SMTP_PORT,
                start_tls=True, username=settings.SMTP_USER, password=settings.SMTP_PASSWORD,
            )
            return True
        except Exception as e:
            logger.warning("email_send_failed", to=to, error=str(e))
            return False

    async def broadcast_telegram(self, chat_ids: list[str], text: str, token: str | None = None) -> dict:
        """Send to multiple Telegram chats. Returns success/fail counts."""
        import asyncio
        results = await asyncio.gather(*[self.telegram(cid, text, token=token) for cid in chat_ids])
        return {"sent": sum(results), "failed": len(results) - sum(results)}

    def format_alert(self, title: str, summary: str, url: str = "", urgency: str = "medium",
                     sentiment: str = "neutral", tags: list[str] | None = None) -> str:
        """Standard alert format for all monitoring products."""
        emoji = {"critical": "🚨", "high": "⚠️", "medium": "ℹ️", "low": "📌"}.get(urgency, "📌")
        sent_emoji = {"positive": "📈", "negative": "📉", "neutral": "➡️", "mixed": "↕️"}.get(sentiment, "")
        tag_line = f"\n🏷️ {' '.join(['#' + t for t in (tags or [])])}" if tags else ""
        link_line = f"\n🔗 [Read more]({url})" if url else ""
        return f"{emoji} *{title[:100]}*\n\n_{summary[:300]}_\n\n{sent_emoji} {sentiment.title()} | Urgency: {urgency.title()}{tag_line}{link_line}"

    def format_digest(self, items: list[dict], title: str = "Daily Digest") -> str:
        """Standard daily digest format."""
        lines = [f"📋 *{title}*\n{'─' * 30}"]
        for i, item in enumerate(items[:10], 1):
            urgency_e = {"critical": "🚨", "high": "⚠️", "medium": "ℹ️", "low": "📌"}.get(item.get("urgency", ""), "📌")
            lines.append(f"\n{i}. {urgency_e} *{item.get('title','')[:70]}*")
            lines.append(f"   {item.get('summary','')[:150]}")
        lines.append(f"\n{'─' * 30}\n_Generated by LateNightStack AI_")
        return "\n".join(lines)


notification_service = NotificationService()
